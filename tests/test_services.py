# Параметризация для разных лимитов и ожидаемых результатов
@pytest.mark.parametrize(
    "month, limit, expected_amount",
    [
        # Пересчитанные значения:
        ("2023-01", 10, 23.56),
        # (1720-1712) + (130-123.45) + (50-50) + (10-1) + (200-199.99) = 8 + 6.55 + 0 + 9 + 0.01 = 23.56
        ("2023-01", 50, 113.56),
        # (1750-1712) + (150-123.45) + (50-50) + (50-1) + (200-199.99) = 38 + 26.55 + 0 + 49 + 0.01 = 113.56
        ("2023-01", 100, 313.56),
        # (1800-1712) + (200-123.45) + (100-50) + (100-1) + (200-199.99) = 88 + 76.55 + 50 + 99 + 0.01 = 313.56
        ("2023-02", 50, 40.00),  # Для 2023-02 есть одна трата: -10.00. Округляем до 50. 50-10 = 40.00
        ("2023-01", 75, 0.00),  # Недопустимый лимит
    ],
)
def test_investment_bank_valid_limits(sample_transactions_for_invest_bank, month, limit, expected_amount):
    """
    Тестирует расчет суммы для Инвесткопилки с допустимыми порогами округления.
    """
    result = investment_bank(month, sample_transactions_for_invest_bank, limit)
    assert result == round(expected_amount, 2)  # Округляем ожидаемую сумму для сравнения


