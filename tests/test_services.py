def test_investment_bank_invalid_limit_logging(caplog):
    """
    Тестирует, что при недопустимом лимите логируется ошибка.
    """
    transactions = [{"Дата операции": "2023-01-15", "Сумма операции": -1712.00}]

    # Временно устанавливаем уровень логгера для src.services, чтобы он ловил ERROR
    # (если он был выше, например, CRITICAL).
    # Здесь он уже настроен на ERROR в src/services.py, так что это просто для надежности.
    # caplog.at_level(logging.ERROR) гарантирует, что caplog будет ловить сообщения
    # от любого логгера, который логирует на уровне ERROR или выше.
    with caplog.at_level(logging.ERROR):
        result = investment_bank("2023-01", transactions, 75)
        assert result == 0.0
        # Проверяем, что сообщение было записано в лог
        assert "Недопустимый порог округления: 75" in caplog.text


def test_investment_bank_transaction_logging(caplog):
    """
    Тестирует логирование для транзакций с некорректными данными.
    """
    transactions = [
        {"Дата операции": "2023-01-15"},  # Нет суммы
        {"Сумма операции": -100.00},  # Нет даты
        {"Дата операции": "2023-01-15", "Сумма операции": "abc"},  # Сумма не число
    ]
    # Настраиваем caplog на захват WARNING сообщений
    with caplog.at_level(logging.WARNING):
        result = investment_bank("2023-01", transactions, 10)
        assert result == 0.0
        # Проверяем, что сообщение было записано в лог
        assert "Пропущена транзакция из-за отсутствия/некорректных данных" in caplog.text
        # Дополнительно: убедимся, что по каждой транзакции было предупреждение
        assert caplog.records  # Убедимся, что есть хоть какие-то записи
        assert len([r for r in caplog.records if "Пропущена транзакция" in r.message]) == 3
